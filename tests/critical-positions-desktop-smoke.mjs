import assert from 'node:assert/strict';
import { once } from 'node:events';
import { app } from 'electron';
import { mkdtempSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { fixtureArchive, hash } from './fixtures/opening-archive.mjs';
import { backfillCriticalPositions } from '../scripts/critical-positions.mjs';

const temporary = mkdtempSync(join(tmpdir(), 'critical-desktop-'));
app.setPath('userData', temporary);
const path = join(temporary, 'archive.sqlite3');
const db = fixtureArchive(path, ['1.e4 $1 $14 $94 $139 $200 {[%crit opening] First solution} (1.d4 {[%medal tactics,attack,sacrifice] Branch solution} d5) e5 2.Nf3 {[%crit endgame] [%medal strategy] Last solution} Nc6 *', '1.d4 d5 *', '1.c4 {[%medal strategy]} e5 *']);
db.close();
backfillCriticalPositions(path);
const original = hash(readFileSync(path));
writeFileSync(join(temporary, 'archive.json'), JSON.stringify({ path }));
const errors = [];
app.on('browser-window-created', (_event, window) => {
  window.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); });
});
async function smoke() {
  const timeout = setTimeout(() => { console.error('Critical-position desktop smoke timed out'); app.exit(1); }, 30000);
  let exitCode = 0;
  try {
    const created = once(app, 'browser-window-created');
    await import('../electron/main.mjs');
    const [, window] = await created;
    await once(window.webContents, 'did-finish-load');
    await window.webContents.executeJavaScript(`(async () => {
      window.waitForCritical = async predicate => {
        const deadline = Date.now() + 5000;
        while (!predicate()) { if (Date.now() > deadline) throw new Error('UI did not update: ' + predicate); await new Promise(resolve => setTimeout(resolve, 25)); }
      };
      window.changeCritical = async value => {
        const root=[...document.querySelectorAll('.property-filter')].find(el=>el.querySelector(':scope > span')?.textContent==='Study markers');
        root.querySelector('.property-trigger').click();await waitForCritical(()=>root.querySelector('[role=option]')&&!root.querySelector('[role=status]'));
        const selected=root.querySelector('[aria-selected=true]');if(selected) {selected.click();await new Promise(resolve=>setTimeout(resolve,250));}
        [...root.querySelectorAll('[role=option]')].find(el=>el.querySelector('span').textContent.replace('✓ ','').toLowerCase()===value).click();
        root.querySelector('[role=combobox]').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
      };
      await waitForCritical(() => document.querySelectorAll('.result-item').length === 3);
      if (!document.querySelector('.game-critical-badge')?.textContent.includes('2 critical')) throw new Error('Missing badge');
      await changeCritical('no');
      await waitForCritical(() => document.querySelectorAll('.result-item').length === 1 && !document.querySelector('.game-critical-badge'));
      await changeCritical('yes');
      await waitForCritical(() => document.querySelectorAll('.result-item').length === 2 && document.querySelector('.game-critical-badge'));
      if (document.querySelector('.game-medal-badge')?.textContent.trim() !== '4 medals' || document.querySelectorAll('.game-medal-badge').length !== 2) throw new Error('Medal counts and medal-only games must be visible');
      document.querySelector('.result-item').click();
      await waitForCritical(() => document.querySelector('.review-shell cg-board'));
      document.querySelector('[aria-label="Game review settings"]').click();
      await waitForCritical(() => document.querySelector('dialog[open]'));
      const descriptionToggle = [...document.querySelectorAll('dialog label')].find(el => el.textContent === 'Show glyph descriptions')?.querySelector('input');
      if (!descriptionToggle || descriptionToggle.checked || document.querySelector('.review-glyph-description')) throw new Error('Glyph descriptions should default off');
      if (document.querySelector('.review-glyph[title="Good move"]')?.textContent !== '!') throw new Error('Missing move glyph hover description');
      if (!document.querySelector('.review-evaluation [title="White has a slight advantage"]')) throw new Error('Missing evaluation glyph hover description');
      if (document.querySelector('.review-glyph[title="White has poor rook placement"]')?.textContent !== '$94') throw new Error('Missing less common glyph description');
      if (!document.querySelector('.review-glyph[title="Annotation $200 (not defined in the PGN specification)"]')) throw new Error('Unknown NAG should have an explicit fallback');
      descriptionToggle.click();
      await waitForCritical(() => document.querySelector('.review-glyph-description'));
      const annotatedMove = document.querySelector('.review-move').textContent;
      if (!annotatedMove.includes('! (Good move)') || !annotatedMove.includes('⩲ (White has a slight advantage)') || !annotatedMove.includes('$94 (White has poor rook placement)')) throw new Error('Enabled glyph descriptions must appear in parentheses');
      await waitForCritical(() => JSON.parse(localStorage.getItem('review-analysis-v1')).glyphDescriptions === true);
      if (document.querySelector('.review-move[aria-current="step"]')) throw new Error('Showing descriptions moved the board');
      descriptionToggle.click();
      await waitForCritical(() => !document.querySelector('.review-glyph-description'));
      const studyToggle = document.querySelector('.review-study-button');
      if (studyToggle.previousElementSibling?.getAttribute('aria-label') !== 'Flip board' || !studyToggle.querySelector('.lucide-eye')) throw new Error('Study setting must be beside Flip board with an eye icon');
      studyToggle.click();
      [...document.querySelectorAll('dialog button')].find(el => el.textContent === 'Done').click();
      await waitForCritical(() => document.querySelectorAll('.review-move').length === 1);
      if (document.querySelector('.review-move[aria-current="step"]')) throw new Error('Enabling study moved the starting position');
      document.querySelector('[aria-label="Next move"]').click();
      await waitForCritical(() => document.querySelector('.review-move[aria-current="step"]')?.textContent.includes('e4'));
      if (document.querySelector('.review-transcript').textContent.includes('solution') || document.querySelector('.review-original')) throw new Error('Hidden commentary leaked');
      document.dispatchEvent(new KeyboardEvent('keydown', { key: 'End', bubbles: true, cancelable: true }));
      document.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true, cancelable: true }));
      await new Promise(resolve => setTimeout(resolve, 50));
      if (!document.querySelector('.review-move[aria-current="step"]')?.textContent.includes('e4')) throw new Error('Keyboard bypassed reveal boundary');
      const checkRevealButton = () => {
        const reveal = document.querySelector('.review-reveal-button');
        const marker = [...(reveal?.previousElementSibling?.querySelectorAll('.review-critical, .review-medal') || [])].at(-1);
        if (!marker || !reveal.querySelector('.lucide-eye') || !reveal.title.includes('without moving the board')) throw new Error('Missing inline eye or explanation');
        const diamond = marker.getBoundingClientRect(), button = reveal.getBoundingClientRect();
        if (button.left < diamond.right || button.left - diamond.right > 16 || button.top > diamond.bottom || button.bottom < diamond.top) throw new Error('Reveal button must sit beside the diamond on the same line');
        if (reveal.closest('.review-move')) throw new Error('Reveal must not be nested inside the move button');
        return reveal;
      };
      const boardState = () => ({ path: document.querySelector('.review-move[aria-current="step"]')?.dataset.reviewPath, pieces: [...document.querySelectorAll('cg-board piece')].filter(el => !el.classList.contains('fading')).map(el => ({ piece: el.className.replace(/\b(anim|drag)\b/g, '').trim(), square: el.style.transform })).sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b))) });
      const sameBoard = before => {
        if (JSON.stringify(before) !== JSON.stringify(boardState())) throw new Error('Reveal changed the current position');
      };
      await new Promise(resolve => setTimeout(resolve, 300));
      let before = boardState();
      checkRevealButton().click();
      await waitForCritical(() => document.querySelectorAll('.review-move').length === 2);
      sameBoard(before);
      if (!document.querySelector('.review-move[aria-current="step"]')?.textContent.includes('e4')) throw new Error('Reveal must keep e4 selected');
      document.querySelector('[aria-label="Next study stop"]').click();
      await waitForCritical(() => document.querySelector('.review-move[aria-current="step"]')?.textContent.includes('d4'));
      await new Promise(resolve => setTimeout(resolve, 300));
      before = boardState();
      checkRevealButton().click();
      await waitForCritical(() => [...document.querySelectorAll('.review-move')].some(el => el.textContent.includes('Nf3')));
      sameBoard(before);
      if (document.querySelector('.review-transcript').textContent.includes('Last solution')) throw new Error('Last solution leaked');
      document.querySelector('[aria-label="Next study stop"]').click();
      await waitForCritical(() => document.querySelector('.review-move[aria-current="step"]')?.textContent.includes('Nf3'));
      await new Promise(resolve => setTimeout(resolve, 300));
      before = boardState();
      checkRevealButton().click();
      await waitForCritical(() => !document.querySelector('.review-reveal-button') && document.querySelector('.review-original'));
      sameBoard(before);
      document.querySelector('[aria-label="Next move"]').click();
      await waitForCritical(() => document.querySelector('.review-move[aria-current="step"]')?.textContent.includes('Nc6'));
      const toggleStudy = async () => {
        await new Promise(resolve => setTimeout(resolve, 300));
        const beforeToggle = boardState(), boardElement = document.querySelector('cg-board');
        document.querySelector('[aria-label="Game review settings"]').click();
        await waitForCritical(() => document.querySelector('dialog[open]'));
        const toggle = document.querySelector('.review-study-button');
        const wasEnabled = toggle.getAttribute('aria-pressed') === 'true';
        toggle.click();
        await waitForCritical(() => document.querySelector('.review-study-button').getAttribute('aria-pressed') === String(!wasEnabled));
        [...document.querySelectorAll('dialog button')].find(el => el.textContent === 'Done').click();
        await new Promise(resolve => setTimeout(resolve, 50));
        sameBoard(beforeToggle);
        if (boardElement !== document.querySelector('cg-board')) throw new Error('Toggling study recreated the board');
      };
      await toggleStudy();
      await toggleStudy();
      if (!document.querySelector('.review-original') || document.querySelector('.review-reveal-button')) throw new Error('No future marker should leave the full score visible');
      document.querySelector('.review-header button').click();
      await waitForCritical(() => !document.querySelector('.review-shell'));
      document.querySelector('.result-item').click();
      await waitForCritical(() => document.querySelectorAll('.review-move').length === 1 && document.querySelector('.review-reveal-button'));
      document.querySelector('[aria-label="Game review settings"]').click();
      await waitForCritical(() => document.querySelector('dialog[open]'));
      [...document.querySelectorAll('dialog button')].find(el => el.textContent === 'Study stops').click();
      [...document.querySelectorAll('dialog button')].find(el => el.textContent === 'Done').click();
      await waitForCritical(() => document.querySelector('.review-original'));
      if (document.querySelector('.review-move[aria-current="step"]')) throw new Error('Disabling study moved the starting position');
      [...document.querySelectorAll('.review-move')].find(el => el.textContent === 'e5').click();
      await waitForCritical(() => document.querySelector('.review-move[aria-current="step"]')?.textContent === 'e5');
      await toggleStudy();
      if (!document.querySelector('.review-reveal-button')?.previousElementSibling.textContent.includes('Nf3') || document.querySelector('.review-original')) throw new Error('Enabling midgame must stop at the next marker');
      await toggleStudy();
      await waitForCritical(() => document.querySelector('.review-original'));
      [...document.querySelectorAll('.review-move')].find(el => el.textContent.includes('d5')).click();
      await waitForCritical(() => document.querySelector('.review-move[aria-current="step"]')?.textContent.includes('d5'));
      await toggleStudy();
      if (!document.querySelector('.review-reveal-button')?.previousElementSibling.textContent.includes('Nf3')) throw new Error('Variation toggle must use score order');
      await toggleStudy();
      document.querySelector('.review-header button').click();
      await waitForCritical(() => !document.querySelector('.review-shell'));
      await changeCritical('no');
      await waitForCritical(() => !document.querySelector('.game-critical-badge'));
      localStorage.setItem('review-analysis-v1', JSON.stringify({ criticalStudy: true }));
      document.querySelector('.result-item').click();
      await waitForCritical(() => document.querySelector('.review-original'));
      if (document.querySelector('.review-reveal-button') || document.querySelector('.review-move[aria-current="step"]')) throw new Error('Unmarked game should open normally');
      document.querySelector('[aria-label="Next move"]').click();
      await waitForCritical(() => document.querySelector('.review-move[aria-current="step"]'));
      const unmarkedScore = document.querySelector('.review-transcript').textContent;
      await toggleStudy();
      await toggleStudy();
      if (document.querySelector('.review-transcript').textContent !== unmarkedScore) throw new Error('Toggling unmarked games should not change annotations');
    })()`);
    assert.deepEqual(errors, []);
    assert.equal(hash(readFileSync(path)), original);
    console.log('Critical-position desktop smoke passed: badges, filters, settings, keyboard boundaries, inline reveal controls, position preservation, normal arrow navigation, persistence, unmarked games, and archive preservation.');
  } catch (error) { console.error(error); exitCode = 1; }
  finally {
    clearTimeout(timeout);
    app.on('will-quit', () => { rmSync(temporary, { recursive: true, force: true }); app.exit(exitCode); });
    app.quit();
  }
}
void smoke();
